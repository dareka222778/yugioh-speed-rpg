'use strict';
const fs=require('node:fs');
const assert=require('node:assert/strict');
const evidence=JSON.parse(fs.readFileSync('docs/evidence/m672-spell-counter-adapter.json','utf8'));
const tests=fs.readFileSync('tests/spellCounterTagAdapter.test.cjs','utf8');
const source=fs.readFileSync('src/spellCounterTagAdapter.ts','utf8');
const certificates=fs.readFileSync('src/cardCertifications.ts','utf8');
assert.equal(evidence.mission,'M672');
assert.equal(evidence.cutoff,'2004-09-30');
assert.equal(evidence.cards.length,3);
assert.equal(evidence.scenarioCount,[...tests.matchAll(/\btest\(/g)].length);
assert.ok(evidence.scenarioCount>=30);
assert.deepEqual(evidence.cards.map(card=>card.id),['70791313','73752131','46363422']);
assert.deepEqual(evidence.cards.map(card=>card.konamiCid),[5658,5649,5648]);
for(const card of evidence.cards){
 assert.ok(card.source.startsWith('https://www.db.yugioh-card.com/yugiohdb/card_search.action?cid='));
 assert.ok(card.firstTcgRelease<='2004-09-30');
 assert.ok(card.officialText.length>40);
}
assert.match(source,/entry\.count<3/);
assert.match(source,/activationZone!=='hand'&&event\.activationZone!=='backrow'/);
assert.match(source,/privateZone\(duel,actorSeat,'hand'\)/);
assert.match(source,/owner%2!==team/);
assert.match(tests,/assertInventoryUnchanged/);
assert.match(tests,/hand privada do parceiro/);
assert.match(tests,/Field Zone separada/);
const certified=[...certificates.matchAll(/^\s*"(\d{8})"\s*:/gm)].map(match=>match[1]);
assert.equal(new Set(certified).size,evidence.engineCertifiedCardsBefore);
assert.equal(evidence.engineCertifiedCardsAfter,evidence.engineCertifiedCardsBefore);
assert.equal(evidence.newCertifications,0);
assert.equal(evidence.automaticCertifications,0);
assert.equal(evidence.inventoryGrants,0);
assert.equal(evidence.behaviorVerifiedCards,3);
assert.equal(evidence.certificationStatus,'adapter-behavior-verified; not engine-v9 certified');
assert.equal(evidence.runtimeIntegration,'pending-explicit-handoff');
assert.equal(evidence.rules.mainDeck,'20–30 por assento físico');
assert.equal(evidence.rules.handLimit,6);
assert.equal(evidence.rules.handCheck,'End Phase');
assert.equal(evidence.rules.monsterZones,3);
assert.equal(evidence.rules.spellTrapZones,3);
assert.equal(evidence.rules.extraDeckMax,5);
assert.equal(evidence.rules.fieldZone,'separada');
assert.equal(evidence.production,'unchanged');
assert.equal(evidence.merge,'not-authorized');
assert.equal(evidence.discordLive,false);
console.log('M672 evidence OK: '+evidence.behaviorVerifiedCards+' adapter behaviors, '+evidence.scenarioCount+' scenarios, '+evidence.engineCertifiedCardsAfter+' engine-v9 certificates, 0 new certificates, 0 inventory grants.');
