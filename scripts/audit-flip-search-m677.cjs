'use strict';
const fs=require('node:fs'),assert=require('node:assert/strict');
const evidence=require('../docs/evidence/m677-flip-search.json');
const tests=fs.readFileSync('tests/flipSearchTagAdapter.test.cjs','utf8');
const source=fs.readFileSync('src/flipSearchTagAdapter.ts','utf8');
